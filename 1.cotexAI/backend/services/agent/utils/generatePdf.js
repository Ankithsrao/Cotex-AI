import PDFDocument from "pdfkit"

export const generatePdf = async (data) => {
    const sections = data?.sections ?? data?.section
    if (typeof data?.title !== "string" || !Array.isArray(sections)) {
        throw new TypeError("PDF data must include a title and sections")
    }
    if (sections.some((section) => (
        typeof section?.heading !== "string" || !Array.isArray(section.points)
    ))) {
        throw new TypeError("Each PDF section must include a heading and points")
    }

    return new Promise((resolve, reject) => {
        const doc = new PDFDocument({
            size: "A4",
            margin: 50,
            info: {
                Author: "CotexAI",
                Title: data.title,
                Creator: "CotexAI"
            }
        })

        const chunks = []

        doc.on("data", (chunk) => chunks.push(chunk))
        doc.on("end", () => resolve(Buffer.concat(chunks)))
        doc.on("error", reject)

        doc
            .fillColor("#118827")
            .fontSize(28)
            .text(data.title, { align: "center" })

        if (typeof data.subtitle === "string" && data.subtitle.trim()) {
            doc
                .moveDown(0.5)
                .fillColor("#6B7280")
                .fontSize(16)
                .text(data.subtitle, { align: "center" })
        }

        doc.moveDown(2)

        sections.forEach((section) => {
            doc
                .fillColor("#111827")
                .fontSize(18)
                .text(section.heading)
                .moveDown(0.5)

            section.points.forEach((point) => {
                doc
                    .fillColor("#374151")
                    .fontSize(12)
                    .text(`• ${point}`, { lineGap: 5 })
            })

            doc.moveDown()
        })

        doc
            .moveDown()
            .fillColor("#9CA3AF")
            .fontSize(10)
            .text("Generated By CotexAI", { align: "center" })

        doc.end()
    })
}